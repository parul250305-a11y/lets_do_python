# Type conversion in Python is the process of changing a value from one data type to another. Python handles this in two distinct ways: implicit conversion (done automatically by the interpreter) and explicit conversion (done manually by the programmer, also known as typecasting).
# Que --> Given a double value d, typecast it to an integer value and print it.

d = float(input("Enter a number : "))  # enter a number like - 5.6 , 4.2, 1.8 (decimal) 

m = int(d)
print(m)
print(type(m))
