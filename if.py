# An if statement in Python allows you to execute a specific block of code only when a certain condition is met. It is the most fundamental tool for decision-making and controlling the flow of a program

# Que --> Given a number n, use the if statement to print "Big" (without quotes) if the given number is greater than 100. The statement "Number" (without quotes) will be printed regardless.

n = int(input("Enter a number: "))

if n > 100 :
    print('Big')
if n > 0:
    print("Number")
    

