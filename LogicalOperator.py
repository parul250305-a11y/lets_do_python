# Logical Operators
# Logical operators perform Logical AND, Logical OR and Logical NOT operations. It is used to combine conditional statements.

# The precedence of Logical Operators in Python is as follows:

# i)   Logical not
# ii)  logical and
# iii) logical or


a = True
b = False
print(a and b) # means both situation must be true or performed when given
print(a or b)  # means either one or both could be true 
print(not a)   # not flips a truth value. If a is True, "not a" becomes False. If a is False, "not a" becomes True.